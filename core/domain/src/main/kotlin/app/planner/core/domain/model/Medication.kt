package app.planner.core.domain.model

import java.time.Instant
import java.time.LocalDate
import java.time.LocalTime

/**
 * Лекарство (или витамин): что принимать, сколько, когда и как долго.
 *
 * ЧЕМ ОТЛИЧАЕТСЯ ОТ ПРИВЫЧКИ. И то и другое повторяется, и расписание у них считает один движок
 * (Recurrence): «каждый день», «по пн и чт», «раз в 3 дня», паузы. Но у лекарства:
 * - несколько приёмов в день ([times]: 9:00 и 21:00), и каждый отмечают отдельно.
 *   У привычки отметка одна на день — поэтому лекарства не «вид привычки», а своя модель;
 * - есть доза и «до / после еды» — их показывают рядом с приёмом;
 * - есть курс: «10 дней» или «до 30 ноября» ([endDate]); бессрочно — витамины на каждый день.
 *
 * Отметки «принято» хранятся отдельно — [DoseTaken], по одной на приём. Само лекарство их не знает:
 * так правка лекарства (другая доза, новое время) не трогает историю.
 *
 * @param dose сколько за раз — свободным текстом: «1 таблетка», «½ таблетки», «5 мл», «2 капли».
 *   Пусто — не показываем. Свободный текст, а не «число + единица»: способов сказать дозу слишком много.
 * @param food как принимать относительно еды; null — неважно.
 * @param times во сколько приёмы в течение дня. Хотя бы один; порядок и повторы не важны —
 *   движок сам отсортирует (см. [doseTimes]).
 * @param repeat в какие дни: каждый день, по дням недели или раз в N дней. «Раз в год» и цикл
 *   у лекарств не бывают — их редактор лекарства не предлагает.
 * @param startDate с какого дня принимать (и точка отсчёта для «раз в N дней»).
 * @param endDate последний день курса включительно; null — бессрочно.
 *   «Курс 10 дней» хранится так же — датой окончания (см. Medications.courseEnd).
 * @param pauses перерывы — как у повторений: «перерыв на неделю», «пауза до визита к врачу».
 * @param remind напоминать о каждом приёме, ровно в его время.
 * @param repeatReminder если на напоминание не ответили — напомнить ещё раз через 10 минут,
 *   и так не больше трёх раз. По желанию: по умолчанию выключено.
 * @param note заметка: «запивать водой», «не вместе с кофе».
 * @param position место в списке лекарств — как расставили перетаскиванием.
 */
data class Medication(
    val id: Long = 0,
    val name: String,
    val dose: String = "",
    val food: FoodRelation? = null,
    val times: List<LocalTime>,
    val repeat: Repeat = Repeat.Daily,
    val startDate: LocalDate,
    val endDate: LocalDate? = null,
    val pauses: List<Pause> = emptyList(),
    val remind: Boolean = true,
    val repeatReminder: Boolean = false,
    val note: String = "",
    val position: Int = 0,
) {
    init {
        require(times.isNotEmpty()) { "Нужен хотя бы один приём в день" }
        require(repeat !is Repeat.Yearly && repeat !is Repeat.Cycle) {
            "У лекарства бывают только «каждый день», «по дням недели» и «раз в N дней»"
        }
        require(endDate == null || endDate >= startDate) { "Курс не может закончиться раньше, чем начался" }
    }

    /** Времена приёмов по порядку и без повторов: 9:00, 14:00, 21:00. */
    val doseTimes: List<LocalTime> get() = times.distinct().sorted()
}

/** Как принимать относительно еды: до, во время, после. */
enum class FoodRelation { BEFORE, WITH, AFTER }

/**
 * Отметка «принято»: лекарство [medicationId] в день [date], приём в [time] (время по расписанию,
 * а не когда на самом деле выпили). [takenAt] — когда нажали «Принято».
 *
 * Отметку снимают — запись удаляется. «Пропущено» отдельно не храним: пропущенный приём —
 * это приём без отметки, он тихо остаётся в своём дне и никуда не переносится.
 *
 * Приём узнаётся по времени, а не по номеру («второй за день»): если добавить приём в 14:00,
 * отметки 9:00 и 21:00 не перепутаются.
 */
data class DoseTaken(
    val medicationId: Long,
    val date: LocalDate,
    val time: LocalTime,
    val takenAt: Instant = Instant.now(),
)
