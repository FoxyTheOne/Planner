package app.planner.core.domain.model

/**
 * Список «Когда-нибудь» — папка для дел без срока: Дом, Книги, Покупки…
 *
 * Задачи ссылаются на список через [Task.listId]. Запланированная задача остаётся
 * в своём списке (серой, с датой), пока её не сделают.
 */
data class TaskList(
    val id: Long = 0,
    val name: String,
    /** Цвет точки-метки у задач этого списка. */
    val color: ListColor = ListColor.SAGE,
    /** Порядок в ряду списков. */
    val position: Int = 0,
    /**
     * Системный список: сюда попадают задачи, которым не выбрали список, и задачи из удалённых списков.
     * В коде он называется inbox («входящие»), а пользователь видит его как «Без списка». Удалить его нельзя.
     */
    val isInbox: Boolean = false,
)

/**
 * Приглушённая палитра меток. Здесь только названия цветов — сами оттенки
 * (свои для светлой и тёмной темы) задаются в дизайн-системе, в `Color.kt`.
 */
enum class ListColor { SAGE, TERRACOTTA, DUSTY_BLUE, LAVENDER, OCHRE, ROSE }
