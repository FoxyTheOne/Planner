package app.planner.core.domain.model

import app.planner.core.domain.recurrence.Recurrence
import java.time.DayOfWeek
import java.time.LocalDate
import java.time.LocalTime

/**
 * Правило повторения: «что делать» + «как часто» + «с какого и до какого дня».
 *
 * Важная идея: повторяющаяся задача хранится ОДИН раз — как правило, а не как 365 задач
 * на год вперёд. Какие дни выпадают на неделю, движок ([Recurrence]) считает на лету.
 * Так правило можно поменять («теперь по вторникам») — и все будущие дни поменяются сразу.
 *
 * Есть: каждый день, по дням недели, раз в N дней, цикл из нескольких недель, паузы.
 * Лекарства и привычки добавим следующими шагами.
 *
 * @param startDate с какого дня правило действует. Для «раз в N дней» это ещё и точка отсчёта.
 * @param endDate по какой день включительно; null — бессрочно.
 * @param pauses периоды, когда правило «молчит» (отпуск, болезнь, каникулы).
 *   Пауза работает «как с музыкой»: после неё повторение продолжается с того места,
 *   где остановилось. Цикл не перескакивает через недели отпуска, «раз в N дней» не считает
 *   дни паузы. Для «каждый день» и «по дням недели» разницы нет — там каждый раз одно и то же.
 */
data class RecurrenceRule(
    val id: Long = 0,
    val title: String,
    val repeat: Repeat,
    val startDate: LocalDate,
    val endDate: LocalDate? = null,
    val pauses: List<Pause> = emptyList(),
    val time: LocalTime? = null,
    val partOfDay: PartOfDay? = null,
    val listId: Long? = null,
)

/**
 * Пауза: с [from] по [until] включительно правило не выпадает.
 *
 * @param until последний день паузы; null — пауза «без даты»: длится, пока человек
 *   не нажмёт «Продолжить» (см. [Recurrence.resume]).
 */
data class Pause(val from: LocalDate, val until: LocalDate? = null) {
    init {
        require(until == null || from <= until) { "Пауза не может закончиться раньше, чем началась" }
    }

    // operator fun contains позволяет писать `date in pause` — как с диапазонами и списками
    operator fun contains(date: LocalDate): Boolean =
        date >= from && (until == null || date <= until)
}

/**
 * Как часто повторяется.
 *
 * `sealed interface` — «закрытый» набор вариантов: все они перечислены здесь, и других
 * быть не может. Зато у каждого варианта свои данные: дням недели нужен набор дней,
 * «раз в N дней» — число N, а «каждый день» не нужно ничего.
 * Когда мы пишем `when (repeat) { ... }`, компилятор проверяет, что разобраны ВСЕ варианты.
 * Добавим новый (например, цикл полива) — компилятор сам покажет места, где его надо учесть.
 *
 * (Альтернатива — enum + куча необязательных полей вроде `days: Set?` и `n: Int?`.
 * Тогда можно случайно создать «раз в N дней» без N. Здесь так не получится.)
 */
sealed interface Repeat {

    /** Каждый день. `data object` — вариант без данных, он один на всё приложение. */
    data object Daily : Repeat

    /** По выбранным дням недели: «пн, ср, пт», «по будням», «по субботам». */
    data class OnWeekdays(val days: Set<DayOfWeek>) : Repeat {
        // init выполняется при создании объекта; require бросит ошибку, если условие нарушено
        init {
            require(days.isNotEmpty()) { "Нужен хотя бы один день недели" }
        }
    }

    /**
     * Раз в N дней, считая от [RecurrenceRule.startDate]: «через день» — это N = 2.
     * Дни паузы в счёт не идут: после паузы отсчёт продолжается с того места, где остановился.
     */
    data class EveryNDays(val n: Int) : Repeat {
        init {
            require(n >= 1) { "N должно быть не меньше 1" }
        }
    }

    /**
     * Цикл из нескольких недель, у каждой недели — свои дела по дням.
     * Пример — полив на 4 недели:
     * ```
     * неделя 1: ср → «фикус, монстера»
     * неделя 2: ср → «фикус» ; сб → «подкормка»
     * неделя 3: ср → «фикус, монстера»
     * неделя 4: ср → «фикус» ; сб → «пересадка, если пора»
     * ```
     * Потом снова неделя 1.
     *
     * Какая неделя цикла идёт сейчас, считается от «опорной» недели: «в неделю, которая
     * начинается с [anchorMonday], шла неделя цикла номер [anchorWeekNumber]». Дальше каждая
     * неделя — следующая по кругу, а недели, целиком ушедшие в паузу, не считаются.
     *
     * Почему опора — пара «понедельник + номер», а не просто «понедельник недели 1»:
     * когда человек говорит «сейчас идёт неделя 3» ([Recurrence.setCurrentWeek]), мы просто
     * записываем «эта неделя — третья». Не нужно вычислять, когда была бы неделя 1 с учётом
     * всех прошлых пауз.
     *
     * @param weeks дела по неделям: `weeks[0]` — неделя 1, в ней «день недели → что сделать».
     *   Дней, которых нет в неделе, в этой неделе цикла просто не бывает.
     * @param anchorMonday понедельник опорной недели. При создании цикла — неделя его начала.
     * @param anchorWeekNumber какая неделя цикла шла в опорную неделю: 1, 2, 3… (как видит человек).
     */
    data class Cycle(
        val weeks: List<Map<DayOfWeek, String>>,
        val anchorMonday: LocalDate,
        val anchorWeekNumber: Int = 1,
    ) : Repeat {
        init {
            require(weeks.isNotEmpty()) { "В цикле должна быть хотя бы одна неделя" }
            require(anchorMonday.dayOfWeek == DayOfWeek.MONDAY) { "Неделя цикла начинается с понедельника" }
            require(anchorWeekNumber in 1..weeks.size) { "Такой недели в цикле нет" }
        }
    }
}
