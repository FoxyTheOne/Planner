package app.planner.core.domain.list

/**
 * Как системный список «Без списка» называется на всех языках приложения.
 *
 * Переводы живут в strings.xml (строка `list_inbox`), а domain — чистый Kotlin
 * и читать ресурсы Android не умеет. Поэтому domain только объявляет, ЧТО ему нужно,
 * а достаёт названия модуль app (`ResourceInboxNames`). Тот же приём, что с репозиториями:
 * интерфейс здесь, реализация там, связывает их Hilt.
 *
 * Так переводы записаны в одном месте — в strings.xml, и ничего не нужно держать в синхроне вручную.
 */
interface IInboxNames {
    /** Названия на всех языках, например {"No list", "Без списка", "Без спіса"}. */
    val all: Set<String>
}
