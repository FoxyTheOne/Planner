package app.planner.core.domain.model

import java.time.LocalTime

/**
 * Напоминание о задаче. Необязательное: у большинства задач его нет (Task.reminder = null).
 *
 * Два вида — смотря есть ли у задачи точное время:
 * - у «10:30 врач» напоминают ДО времени: «в момент», «за 10 минут», «за час». Перенесли врача
 *   на 11:00 — напоминание «за 30 минут» само сдвинулось вместе с ним: хранится не час, а «насколько раньше»;
 * - у «купить подарок» в субботу времени нет — напоминают в выбранный час её дня: «в 9:00».
 *   Сама задача при этом остаётся без времени — в плане она по-прежнему «в любое время».
 *
 * `sealed interface`, как Repeat: у вариантов разные данные (минуты или час), а `when (reminder)`
 * обязан разобрать оба. Когда именно сработает напоминание, считает [app.planner.core.domain.reminder.Reminders].
 */
sealed interface Reminder {

    /** За [minutes] минут до времени задачи; 0 — ровно в её время. Только у задач со временем. */
    data class BeforeTime(val minutes: Int) : Reminder {
        init {
            require(minutes >= 0) { "Напоминание не может быть после времени задачи" }
        }
    }

    /** В [time] в день задачи. Для задач без времени. */
    data class AtTime(val time: LocalTime) : Reminder
}
